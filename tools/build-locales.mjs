// Reproducible, offline locale bundle. Edit locales/de.json; reviewed product terms win.
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { pick } = require('../i18n.js');
const de = { ...JSON.parse(readFileSync(new URL('../locales/de.json', import.meta.url))), ...JSON.parse(readFileSync(new URL('../locales/de-reviewed.json', import.meta.url))) };
for (const [source, translated] of Object.entries(de)) {
  if (!pick(source, translated)) throw new Error(`Invalid German translation: ${source}`);
}
writeFileSync(new URL('../dusk-locales.js', import.meta.url), `// Generated by tools/build-locales.mjs. English/German UI works offline.\n(function(root) { const de = ${JSON.stringify(de, null, 2)};\nif (typeof module !== 'undefined' && module.exports) module.exports = { de };\nelse root.DuskLocales = { de };\n})(typeof window !== 'undefined' ? window : globalThis);\n`);
